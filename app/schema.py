from pydantic import BaseModel, Field
from typing import List, Annotated, Literal, TypedDict, Optional, Any

class IntentOutput(BaseModel):
    intent: Annotated[List[Literal["risk_analysis", "summary", "query_answer"]], Field(
        default=["query_answer"],
        description="List of intents of the query. Return one or more of [risk_analysis, summary, query_answer]."
    )]

class QueryOutput(BaseModel):
    answer: Annotated[str, Field(description="Clear, well-reasoned answer or analysis generated by the legal assistant")]
    page_numbers: Annotated[List[int], Field(default_factory=list, description="List of 1-based page numbers where relevant clauses were found")]
    risk_level: Annotated[Optional[Literal["low", "medium", "high", "none"]], Field(default=None, description="Optional overall risk severity: low, medium, high, or none")]
    key_clauses: Annotated[Optional[List[str]], Field(default=None, description="Optional list of key clauses or excerpt quotes identified")]

class SubqueriesOutput(BaseModel):
    subqueries: Annotated[List[str], Field(description="List of 2-3 focused subqueries to retrieve relevant clauses")]

class ComplianceOutput(BaseModel):
    answer: Annotated[str, Field(description="Answer generated by the LLM for the compliance check")]
    compliant: Annotated[Optional[bool], Field(default=None, description="Whether the analyzed excerpt appears compliant")]

class GraphState(TypedDict, total=False):
    query: str
    memory: List[dict]
    context: Any
    intents: List[str]
    rag_answer_node: Any
    summary_node: Any
    risk_analysis_node: Any
    final_answer: Any